// ---------------------------------------------------------------------------
// The seeder
// ---------------------------------------------------------------------------

export const catalogue: Seeder = {
    name: "catalogue",
    kind: "reference",
    description: "Catalogue items in every category",
    needs: ["categories"],
    async run({ prisma, log }) {
        const bySlug = new Map((await prisma.category.findMany({ select: { id: true, slug: true } })).map((c) => [c.slug, c.id]))
        let total = 0
        for (const root of ROOTS) {
            for (const cat of root.categories) {
                const categoryId = bySlug.get(cat.slug)
                if (!categoryId) throw new SeedError(`Category "${cat.slug}" is missing. Run: npm run seed categories`)
                for (const item of cat.items) {
                    const slug = slugify(`${cat.slug}-${item.name}`)
                    const unit = item.unit ?? Unit.PIECE
                    await prisma.catalogItem.upsert({
                        where: { slug },
                        update: { name: item.name, unit, categoryId, isActive: true },
                        create: { name: item.name, slug, unit, categoryId, isActive: true },
                    })
                    total++
                }
                log(`${cat.name}: ${cat.items.length} items`)
            }
        }
        return `${total} catalogue items`
    },
}

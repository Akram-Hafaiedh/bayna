// scripts/make-baseline.ts
// Squashes every migration into ONE baseline: the table definitions Prisma generates from schema.prisma,
// followed by prisma/audit.sql (the audit triggers, which Prisma cannot express).
//
//   npm run db:baseline
//
// It deletes the old folders in prisma/migrations. Only use it while no database that matters depends on
// the old migration history (a development database you can drop and re-seed). After it:
//   drop and recreate the database, then  npx prisma migrate dev  (applies the baseline), then  npm run seed
import { execSync } from "node:child_process"
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = process.cwd()
const migrations = join(root, "prisma", "migrations")
const audit = join(root, "prisma", "audit.sql")

if (!existsSync(audit)) throw new Error("prisma/audit.sql is missing")

const ddl = execSync("npx prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script", {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
})
if (!/CREATE TABLE "Shop"/.test(ddl)) throw new Error('The generated SQL has no CREATE TABLE "Shop": the schema was not read correctly')

mkdirSync(migrations, { recursive: true })
for (const name of readdirSync(migrations)) {
    const p = join(migrations, name)
    if (statSync(p).isDirectory()) rmSync(p, { recursive: true, force: true })
}

const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14)
const dir = join(migrations, `${stamp}_baseline`)
mkdirSync(dir)
const sql = `-- Baseline: the whole schema in one migration (squashed from the earlier history).\n-- Tables: generated by Prisma from schema.prisma. Triggers: prisma/audit.sql.\n\n${ddl.trim()}\n\n${readFileSync(audit, "utf8").trim()}\n`
writeFileSync(join(dir, "migration.sql"), sql)
if (!existsSync(join(migrations, "migration_lock.toml"))) writeFileSync(join(migrations, "migration_lock.toml"), 'provider = "postgresql"\n')
console.log(`Wrote ${dir}`)
